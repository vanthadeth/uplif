-- Exchange rates for payroll.
begin;
create extension if not exists pgtap with schema extensions;
set local search_path = public, extensions;
select no_plan();
insert into auth.users (id, aud, role, email) values ('fd000000-0000-0000-0000-000000000001', 'authenticated', 'authenticated', 'rate-owner@test.local');
insert into public.profiles (user_id, full_name) values ('fd000000-0000-0000-0000-000000000001', 'Owner');
select set_config('request.jwt.claims', json_build_object('sub', 'fd000000-0000-0000-0000-000000000001', 'role', 'authenticated', 'app_metadata', json_build_object())::text, true);
set local role authenticated;
select public.create_company('Rate Co', null, 'PS', 'KHR', 'Main');
reset role;
create temp table m_Rate as select c.id cid, m.id mid from public.companies c join public.memberships m on m.company_id = c.id where c.name = 'Rate Co';
select set_config('request.jwt.claims', json_build_object('sub', 'fd000000-0000-0000-0000-000000000001', 'role', 'authenticated', 'app_metadata', json_build_object('company_id', (select cid from m_Rate), 'membership_id', (select mid from m_Rate)))::text, true);
set local role authenticated;
select lives_ok($$select public.payroll_rate_set('usd', 4100, current_date - 10)$$, 'the owner sets a rate');
select lives_ok($$select public.payroll_rate_set('USD', 4050, current_date - 1)$$, 'and a newer one');
select throws_ok($$select public.payroll_rate_set('KHR', 1, current_date)$$, 'P0001', null, 'the home currency takes no rate');
select throws_ok($$select public.payroll_rate_set('USD', 0, current_date)$$, 'P0001', null, 'a rate must be above zero');
select is((select count(*)::int from public.exchange_rates), 2, 'the owner can read the rates');
reset role;
create temp table c as select id from public.companies where name = 'Rate Co';
select is(app.rate_for((select id from c), 'USD', current_date), 4050.00000000::numeric, 'the latest rate on or before the day applies');
select is(app.rate_for((select id from c), 'USD', current_date - 5), 4100.00000000::numeric, 'an earlier day uses the earlier rate');
select is(app.rate_for((select id from c), 'KHR', current_date), 1::numeric, 'the home currency is 1');
select is(app.rate_for((select id from c), 'EUR', current_date), null, 'an unknown currency has no rate');
select is(app.rate_for((select id from c), 'USD', current_date - 30), null, 'nothing before the first rate');
-- another company cannot see or change them
insert into auth.users (id, aud, role, email) values ('fd000000-0000-0000-0000-000000000002', 'authenticated', 'authenticated', 'rate-other@test.local');
insert into public.profiles (user_id, full_name) values ('fd000000-0000-0000-0000-000000000002', 'Other');
select set_config('request.jwt.claims', json_build_object('sub', 'fd000000-0000-0000-0000-000000000002', 'role', 'authenticated', 'app_metadata', json_build_object())::text, true);
set local role authenticated;
select public.create_company('Other Co', null, 'PS', 'USD', 'Main');
reset role;
create temp table m_Other as select c.id cid, m.id mid from public.companies c join public.memberships m on m.company_id = c.id where c.name = 'Other Co';
select set_config('request.jwt.claims', json_build_object('sub', 'fd000000-0000-0000-0000-000000000002', 'role', 'authenticated', 'app_metadata', json_build_object('company_id', (select cid from m_Other), 'membership_id', (select mid from m_Other)))::text, true);
set local role authenticated;
select is((select count(*)::int from public.exchange_rates), 0, 'another company sees none');
select throws_ok($$select public.payroll_rate_delete((select id from public.exchange_rates limit 1))$$, 'P0002', null, 'and cannot delete them');
reset role;
select * from finish();
rollback;
